#!/usr/bin/env bash
# Regenerates the Solar release table from the `sha256.sum` file of each Solar release.
#
# Run it after a Solar release and commit the result, so installs check the archive against a
# checksum pinned in this repository instead of one served next to the archive.
set -euo pipefail

cd "$(dirname "$0")/.."

repo="paradigmxyz/solar"
out="crates/compilers/crates/compilers/src/compilers/solc/solar_releases.rs"
# Releases before 0.2.0 do not report their Solar version, so they cannot be pinned.
min="0.2.0"

versions=$(
    git ls-remote --tags --refs "https://github.com/$repo" 'v*' |
        sed -E 's|.*refs/tags/v||' |
        grep -E '^[0-9]+\.[0-9]+\.[0-9]+$' |
        sort -t. -k1,1n -k2,2n -k3,3n |
        awk -v min="$min" '{
            split($0, v, "."); split(min, m, ".");
            if (v[1] > m[1] || (v[1] == m[1] && (v[2] > m[2] || (v[2] == m[2] && v[3] >= m[3])))) print
        }'
)

# Writes to a temporary file next to the table and moves it into place only after generation and
# formatting succeed, so a failed download leaves the checked-in table untouched.
tmp=$(mktemp "$(dirname "$out")/.solar_releases.XXXXXX")
trap 'rm -f "$tmp"' EXIT

{
    echo "//! Solar releases with the SHA-256 checksum of each release archive."
    echo "//!"
    echo "//! Generated by \`scripts/update-solar-releases.sh\`. Do not edit."
    echo
    echo "use super::solar_release::SolarRelease;"
    echo "use alloy_primitives::hex;"
    echo "use semver::Version;"
    echo
    echo "/// Solar releases, oldest first."
    echo "pub(super) const SOLAR_RELEASES: &[SolarRelease] = &["
    for version in $versions; do
        IFS=. read -r major minor patch <<<"$version"
        sums=$(curl -fsSL "https://github.com/$repo/releases/download/v$version/sha256.sum")
        echo "    SolarRelease {"
        echo "        version: Version::new($major, $minor, $patch),"
        echo "        archives: &["
        echo "$sums" | sed -E 's/^([0-9a-f]{64}) [ *]?(.*)$/\2 \1/' | sort | while read -r file sha; do
            case "$file" in
                solar-*.tar.gz | solar-*.zip)
                    echo "            (\"$file\", hex!(\"$sha\")),"
                    ;;
            esac
        done
        echo "        ],"
        echo "    },"
    done
    echo "];"
} >"$tmp"
rustfmt +nightly --edition 2024 "$tmp"
chmod 644 "$tmp"
mv "$tmp" "$out"
echo "wrote $out"
